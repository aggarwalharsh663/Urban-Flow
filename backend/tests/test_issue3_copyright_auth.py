# 9. Existing IPC actions still work
def test_existing_ipc_actions_still_work(setup_ipc_env):
    """Verify existing IPC actions remain fully operational with scoped permissions."""
    session_token = setup_ipc_env

    # 1. health (read)
    h_res = ipc_worker.process_ipc_request({
        "id": "req-h",
        "action": "health",
        "token": session_token,
        "scope": "read",
        "data": {},
    })
    assert h_res["ok"] is True
    assert h_res["result"]["status"] == "ok"

    # 2. directions (read)
    d_res = ipc_worker.process_ipc_request({
        "id": "req-d",
        "action": "directions",
        "token": session_token,
        "scope": "read",
        "data": {},
    })
    assert d_res["ok"] is True
    assert "North" in d_res["result"]["directions"]

    # 3. simulate (reports:write)
    s_res = ipc_worker.process_ipc_request({
        "id": "req-s",
        "action": "simulate",
        "token": session_token,
        "scope": "reports:write",
        "data": {"counts": {"North": 10, "South": 10, "East": 10, "West": 10}},
    })
    assert s_res["ok"] is True
    assert "report_id" in s_res["result"]

    # 4. cancel (admin)
    c_res = ipc_worker.process_ipc_request({
        "id": "req-c",
        "action": "cancel",
        "token": session_token,
        "scope": "admin",
        "data": {"cancel_id": "job_123"},
    })
    assert c_res["ok"] is True
    assert c_res["result"]["cancelled"] == "job_123"


# 10. Unauthorized actions remain rejected
def test_unauthorized_actions_remain_rejected(setup_ipc_env):
    """Verify actions requiring elevated scopes are rejected when requested with lower scopes."""
    read_token = security_config.generate_scoped_token("read")

    # Calling 'simulate' with a read token must be rejected
    sim_res = ipc_worker.process_ipc_request({
        "id": "req-sim-unauth",
        "action": "simulate",
        "token": read_token,
        "data": {"counts": {"North": 5, "South": 5, "East": 5, "West": 5}},
    })
    assert sim_res["ok"] is False
    assert "Unauthorized" in sim_res["error"]

    # Calling 'cancel' with a read token must be rejected
    cancel_res = ipc_worker.process_ipc_request({
        "id": "req-cancel-unauth",
        "action": "cancel",
        "token": read_token,
        "data": {"cancel_id": "job_999"},
    })
    assert cancel_res["ok"] is False
    assert "Unauthorized" in cancel_res["error"]
